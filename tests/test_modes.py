"""Pure contracts for game modes and movement courses (verified live in CS2)."""
import json
import math
import unittest
from unittest import mock

from cs2map import modes
from cs2map.project import OpError, Project
from cs2map.vmap import VMap
from tests.helpers import HAVE_CS2, SETTINGS


class ModesPure(unittest.TestCase):
    def test_native_mode_table_matches_cs2_launch_contract(self):
        self.assertEqual(modes.NATIVE["deathmatch"], (1, 2))
        self.assertEqual(modes.NATIVE["armsrace"], (1, 0))
        self.assertEqual(modes.NATIVE["wingman"], (0, 2))
        self.assertEqual(modes.NATIVE["casual"], (0, 0))

    def test_names_are_c2_owned_and_mode_is_strict(self):
        with self.assertRaises(OpError):
            modes._name("dm")
        with self.assertRaises(OpError):
            modes._int(True, "bots", 2, 20)

    def test_mode_script_contains_real_round_reset_and_report_hooks(self):
        code = modes._mode_code({"name": "c2_dm_mode", "mode": "deathmatch",
                                 "equip": None, "weapon": "weapon_ak47"})
        self.assertIn("OnPlayerKill", code)
        self.assertIn("OnPlayerReset", code)
        self.assertIn("C2_MODE stats", code)
        self.assertIn('"mp_freezetime 0"', code)
        # Deathmatch respawn is selected by native game_type/game_mode; the
        # generated script records the real kill/reset events.
        self.assertNotIn("mp_respawn_on_death_t 1", code)
        surf = modes._mode_code({"name": "c2_surf_mode", "mode": "surf",
                                 "equip": None, "weapon": "weapon_ak47"})
        self.assertIn("mp_respawn_on_death_t 1", surf)
        self.assertIn('"mp_freezetime 0"', surf)

    def test_course_runtime_has_per_player_checkpoint_and_timer(self):
        source = modes.COURSE_RUNTIME
        self.assertIn("states=new Map", source)
        self.assertIn("checkpoint", source)
        self.assertIn("C2_TIMER", source)
        self.assertIn("Teleport", source)

    def test_unpack_preserves_json_request_without_nan(self):
        raw = {"op": "add_mode", "name": "c2_dm", "mode": "deathmatch"}
        out = modes._unpack({"_mode_request": json.dumps(raw)})
        self.assertEqual(out, raw)
        with self.assertRaises(ValueError):
            json.dumps({"x": float("nan")}, allow_nan=False)

    def test_mode_test_restores_settings_after_load_failure(self):
        p = mock.Mock()
        p.load.return_value = object()
        names = ['game_type','game_mode','sv_airaccelerate','sv_autobunnyhopping','sv_enablebunnyhopping',
                 'mp_respawn_on_death_t','mp_respawn_on_death_ct','mp_ignore_round_win_conditions',
                 'mp_freezetime','mp_limitteams','mp_autoteambalance','mp_warmuptime','bot_quota']
        with mock.patch.object(modes,'_records',return_value=[(None,{'mode':'deathmatch','name':'c2_test'})]), \
             mock.patch.object(modes.game,'exclusive'), \
             mock.patch.object(modes.game,'query',return_value=[f'{k} = 0' for k in names]), \
             mock.patch.object(modes.game,'load_map',side_effect=RuntimeError('load failed')), \
             mock.patch.object(modes.game,'ensure_map') as idle, \
             mock.patch.object(modes.game,'command') as cmd:
            with self.assertRaisesRegex(RuntimeError,'load failed'):
                modes.mode_playtest(p,'c2_test')
            self.assertEqual(idle.call_args.args[1],'mcp_idle')
            self.assertIn('game_type 0',cmd.call_args.args[1])
            self.assertIn('game_mode 0',cmd.call_args.args[1])


@unittest.skipUnless(HAVE_CS2,'Installed FGD/templates needed')
class ModesAuthoring(unittest.TestCase):
    def setUp(self):
        self.p = Project()
        self.m = VMap.from_template(SETTINGS.cs2_path,'empty')
        self.token = modes.PREVIEW.set(True)
    def tearDown(self):
        modes.PREVIEW.reset(self.token)

    def test_missing_wingman_objective_refused(self):
        with self.assertRaisesRegex(OpError,'one bombsite'):
            modes.add_mode(self.p,self.m,{'op':'add_mode','name':'c2_unit','mode':'wingman'}, {})
        self.assertEqual(len(self.m.entities()),0)

    def test_spawn_entity_classes_and_dm_disable_autogeneration(self):
        for mode,cls in [('deathmatch','info_deathmatch_spawn'),('armsrace','info_armsrace_terrorist')]:
            m = VMap.from_template(SETTINGS.cs2_path,'empty')
            out = modes.add_mode(self.p,m,{'op':'add_mode','name':'c2_unit_'+mode,'mode':mode,
                                         'spawns':[[128,128,8],[512,128,8],[128,512,8],[512,512,8]]}, {})
            self.assertTrue(m.entities(classname=cls))
            self.assertEqual(out['requires_native_reload'],True)
            if mode=='deathmatch':
                self.assertEqual(m.entities(classname='info_map_parameters')[0]['entity_properties']['disableautogenerateddmspawns'],'1')
            with self.assertRaisesRegex(OpError,'already has'):
                modes.add_mode(self.p,m,{'op':'add_mode','name':'c2_again','mode':mode,'spawns':[[1,1,8],[100,100,8]]}, {})

    def test_surf_angle_is_crosswise_and_ref_resolves(self):
        from cs2map import checks
        refs = {}
        out = modes.add_surf_ramp(self.p,self.m,{'op':'add_surf_ramp','origin':[0,0,0],
                                  'length':512,'width':128,'angle':55,'ref':'ramp'},refs)
        lo,hi = checks._mesh_bounds(self.m.node(out['ids'][0]))
        self.assertEqual(hi[0]-lo[0],512)
        self.assertEqual(hi[1]-lo[1],128)
        self.assertAlmostEqual(hi[2]-lo[2],128*math.tan(math.radians(55)),places=4)
        self.assertEqual(refs['ramp'],out['ids'][0])
        with self.assertRaises(OpError):
            modes.add_surf_ramp(self.p,self.m,{'op':'add_surf_ramp','angle':75},{})

    def test_course_has_real_teleport_and_per_player_checkpoint_resource(self):
        out = modes.add_movement_course(self.p,self.m,{'op':'add_movement_course','name':'c2_unit_course','mode':'kz',
            'spawn':[0,0,8],'start':{'mins':[0,0,0],'maxs':[128,128,128]},
            'finish':{'mins':[1000,0,0],'maxs':[1128,128,128]},'fall':{'mins':[-128,-128,-128],'maxs':[1200,512,-32]},
            'checkpoints':[{'mins':[512,0,0],'maxs':[640,128,128],'destination':[576,64,8]}],
            'hud_layout':None}, {})
        trigger = self.m.entities(classname='trigger_teleport')[0]
        self.assertEqual(trigger['entity_properties']['target'],'c2_unit_course_return')
        self.assertEqual(out['checkpoints'],1)
        self.assertEqual(modes.check_modes(self.p,self.m),[])

    def test_arena_spawns_mirror_cover_and_equip(self):
        modes.add_arena(self.p,self.m,{'op':'add_arena','name':'c2_unit_arena','covers':4}, {})
        t,ct = self.m.entities(classname='info_player_terrorist'),self.m.entities(classname='info_player_counterterrorist')
        self.assertEqual((len(t),len(ct)),(10,10))
        self.assertAlmostEqual(t[0]['origin'][0]+ct[0]['origin'][0],1536)
        self.assertTrue(self.m.entities(classname='game_player_equip'))

    def test_batch_preflight_refuses_later_error_without_script_write(self):
        p = mock.Mock()
        p._lock = __import__('threading').RLock()
        original = mock.Mock(side_effect=OpError('later invalid op'))
        wrapped = modes.map_edit_wrapper(p,original)
        with mock.patch.object(modes.scripting,'script_write') as write:
            with self.assertRaisesRegex(OpError,'later invalid'):
                wrapped('c2_unit',[{'op':'add_mode'}])
            write.assert_not_called()
            self.assertTrue(original.call_args.args[2])


if __name__ == "__main__":
    unittest.main()
