"""map_build(name, "release"): one map in its own addon with only the files it uses; feedback for the author."""
import dataclasses
import json
import os
import shutil
import unittest
import uuid

from cs2map import mylayer, release
from tests.helpers import HAVE_COMPILER, ROOT, agent_suffix

MAP = 'test_release' + agent_suffix()


@unittest.skipUnless(HAVE_COMPILER, 'CS2 install not found or CS2MAP_OFFLINE set (add_hud compiles)')
class Release(unittest.TestCase):
    def test_release_copies_only_what_the_map_uses_and_refuses_foreign_addons(self):
        from cs2map import server
        p = server.project
        p.map_create(MAP, 'basic', overwrite=True)
        p.map_edit(MAP, [{'op': 'add_entity', 'classname': 'info_player_terrorist', 'origin': [0, 0, 8]},
                         {'op': 'add_hud', 'name': 'rel_card', 'origin': [0, 0, 16],
                          'xml': '<root><Panel class="Root"><Label id="t" text="REL" /></Panel></root>',
                          'css': '.Root { width: 100%; } #t { color: white; }'}])
        found = release.collect(p.s, MAP)
        self.assertIn('panorama/layout/custom_game/mcp_hud_rel_card.xml', found['files'])
        self.assertIn('panorama/styles/custom_game/mcp_hud_rel_card.css', found['files'])
        self.assertFalse([f for f in found['files'] if f.startswith('maps/') and f.endswith('.vmap')])
        addon = 'test_rel_' + uuid.uuid4().hex[:6]
        rs = dataclasses.replace(p.s, addon=addon)
        try:
            plan = release.prepare(p, MAP, addon)
            self.assertTrue((rs.content_addon / release.MARKER).is_file())
            self.assertTrue((rs.content_addon / 'maps' / f'{MAP}.vmap').is_file())
            self.assertTrue((rs.content_addon / 'panorama/styles/custom_game/mcp_hud_rel_card.css').is_file())
            self.assertIn(f'maps/{MAP}.vmap', plan['files'])
            release.prepare(p, MAP, addon)                      # its own release addon: rebuilt in place
            with self.assertRaises(release.ReleaseError):      # an addon the release did not make
                release.prepare(p, MAP, 'cs_script_demo')
            with self.assertRaises(release.ReleaseError):
                release.prepare(p, MAP, p.s.addon)
        finally:
            for folder in (rs.content_addon, rs.game_addon):    # generated by this test
                shutil.rmtree(folder, ignore_errors=True)

    def test_panorama_paths_resolve_to_the_panorama_folder(self):
        refs = release._refs('<include src="file://{resources}/styles/custom_game/a.css" />'
                             '<Image src="file://{images}/custom_game/b.png" /> models/mcp/x/x.vmdl')
        self.assertEqual(refs, {'panorama/styles/custom_game/a.css', 'panorama/images/custom_game/b.png',
                                'models/mcp/x/x.vmdl'})


class Feedback(unittest.TestCase):
    def setUp(self):
        self.dir = ROOT / '.local' / 'tmp' / f'my_fb_{uuid.uuid4().hex[:8]}'
        self.old = os.environ.get('CS2MAP_MY')
        os.environ['CS2MAP_MY'] = str(self.dir)

    def tearDown(self):
        if self.old is None:
            os.environ.pop('CS2MAP_MY', None)
        else:
            os.environ['CS2MAP_MY'] = self.old
        shutil.rmtree(self.dir, ignore_errors=True)

    def test_feedback_is_one_file_with_short_unique_entries(self):
        self.assertEqual(mylayer.feedback_count(), 0)
        out = mylayer.feedback_write('add_facade', 'Wanted balconies on a 2-floor row; got none; added models by hand.')
        self.assertEqual((out['entries'], out['file']), (1, 'my/feedback.md'))
        again = mylayer.feedback_write('add_facade', 'Wanted balconies on a 2-floor row; got none; added models by hand.')
        self.assertEqual(again.get('note'), 'already recorded')
        mylayer.feedback_write('script_test', 'aim step timed out on a moving car')
        text = mylayer.feedback_read()['text']
        self.assertTrue(text.startswith('# Feedback for CS2 Map MCP'))
        self.assertEqual(mylayer.feedback_count(), 2)
        with self.assertRaises(mylayer.MyError):
            mylayer.feedback_write('x', 'y' * 2000)
        self.assertEqual(mylayer.list_all()['feedback'], 2)


if __name__ == '__main__':
    unittest.main()
