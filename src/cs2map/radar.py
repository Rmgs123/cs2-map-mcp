"""Radar (overview) of a map, drawn offline from its geometry, as CS2 shows it in the corner and the scoreboard.

CS2 reads `resource/overviews/<map>.txt` (upper-left world corner pos_x/pos_y and units per pixel) and the image
`panorama/images/overheadmaps/<map>_radar_psd.vtex` (a 1024 x 1024 picture, made from a .psd). Floors are filled by height (higher =
lighter), walls drawn dark, so a player reads the layout at a glance. Made on every full/final build unless the
author keeps an own overview (no cs2map marker in the .txt). Spawn and bomb site positions go to the loading screen.
"""
from __future__ import annotations

import math
from pathlib import Path

from . import meshops
from .config import ensure_inside

MARK = '// generated by cs2map'
SIZE = 1024
BG = (18, 22, 27, 255)
LOW, HIGH = (58, 70, 80), (156, 170, 180)
WALL = (10, 13, 16, 255)
SKIP = ('tools', 'materials/dev/toolslightmapres')


def write_psd(img, path: Path) -> None:
    """A minimal uncompressed 8-bit RGB Photoshop file (all resourcecompiler needs to make a texture)."""
    import struct
    rgb = img.convert('RGB')
    w, h = rgb.size
    planes = b''.join(band.tobytes() for band in rgb.split())
    data = (b'8BPS' + struct.pack('>H6xHIIHH', 1, 3, h, w, 8, 3) + struct.pack('>I', 0) + struct.pack('>I', 0)
            + struct.pack('>I', 0) + struct.pack('>H', 0) + planes)
    path.write_bytes(data)


def _solid_polys(m):
    for node in m.iter_nodes():
        if node.type != 'CMapMesh' or node.get('physicsType') == 'none':
            continue
        mats = [str(x) for x in node['meshData'].get('materials', [])]
        if mats and all('/tools/' in x for x in mats):
            continue
        try:
            polys = meshops.decode_node(node)
        except (ValueError, KeyError):
            continue
        for p in polys:
            if '/tools/' in p.material:
                continue
            yield p


def _playable(m, floors):
    """Floors a player walks on: inside layout rooms near their floor height (roofs, backdrops and the ground under
    the whole map are left out); without a layout, floors no higher than the spawns + 256."""
    from . import route
    rooms = route._layout_rooms(m)[0]
    if rooms:
        out = []
        for z, poly in floors:
            cx, cy = sum(x for x, _ in poly) / len(poly), sum(y for _, y in poly) / len(poly)
            for r in rooms.values():
                lo, hi = r['interior']['mins'], r['interior']['maxs']
                fz = r.get('floor_z', lo[2])
                if lo[0] - 1 <= cx <= hi[0] + 1 and lo[1] - 1 <= cy <= hi[1] + 1 and fz - 40 <= z <= fz + 300:
                    out.append((z, poly))
                    break
        if out:
            return out
    spawns = [e.get('origin')[2] for cls in ('info_player_terrorist', 'info_player_counterterrorist')
              for e in m.entities(classname=cls)]
    top = max(spawns) + 256 if spawns else max(z for z, _ in floors)
    return [(z, poly) for z, poly in floors if z <= top]


def draw(m):
    """(PIL image, pos_x, pos_y, scale) or None when the map has no floors."""
    from PIL import Image, ImageDraw
    floors, walls = [], []
    for p in _solid_polys(m):
        try:
            n = p.n
        except ValueError:
            continue
        pts = [c.p for c in p.corners]
        if n[2] > 0.7:
            floors.append((sum(q[2] for q in pts) / len(pts), [(q[0], q[1]) for q in pts]))
        elif abs(n[2]) < 0.3 and max(q[2] for q in pts) - min(q[2] for q in pts) > 24:
            xy = [(q[0], q[1]) for q in pts]
            a, b = max(((u, v) for u in xy for v in xy), key=lambda uv: (uv[0][0] - uv[1][0]) ** 2 + (uv[0][1] - uv[1][1]) ** 2)
            walls.append((max(q[2] for q in pts), a, b))
    floors = _playable(m, floors)
    if not floors:
        return None
    from . import visual
    play = visual.playable_bounds(m)       # backdrops, terrain beyond the play area and tool volumes left out
    if play:
        (x0, y0, _), (x1, y1, _) = play
    else:
        xs = [x for _, poly in floors for x, _ in poly]
        ys = [y for _, poly in floors for _, y in poly]
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    span = max(x1 - x0, y1 - y0) * 1.06 + 64
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    pos_x, pos_y = cx - span / 2, cy + span / 2
    scale = span / SIZE
    img = Image.new('RGBA', (SIZE, SIZE), BG)
    d = ImageDraw.Draw(img)
    zs = [z for z, _ in floors]
    z_lo, z_hi = min(zs), max(zs)

    def px(x, y):
        return ((x - pos_x) / scale, (pos_y - y) / scale)
    for z, poly in sorted(floors, key=lambda f: f[0]):
        t = 0 if z_hi - z_lo < 1 else (z - z_lo) / (z_hi - z_lo)
        color = tuple(int(LOW[i] + (HIGH[i] - LOW[i]) * t) for i in range(3)) + (255,)
        d.polygon([px(x, y) for x, y in poly], fill=color)
    width = max(2, int(round(10 / scale)))
    for _, a, b in walls:
        d.line([px(*a), px(*b)], fill=WALL, width=width)
    return img, pos_x, pos_y, scale


def write(project, name: str, force: bool = False) -> dict:
    """Write the radar image and the overview file for map `name`; returns paths (or why it was skipped)."""
    s = project.s
    overview = ensure_inside(s.game_addon / 'resource' / 'overviews' / f'{name}.txt', s.game_addon)
    if overview.is_file() and MARK not in overview.read_text(encoding='utf-8', errors='replace') and not force:
        return {'skipped': 'an own overview exists (resource/overviews/%s.txt without the cs2map marker)' % name}
    m = project.load(name)
    made = draw(m)
    if made is None:
        return {'skipped': 'no floors to draw'}
    img, pos_x, pos_y, scale = made
    # CS2 loads panorama/images/overheadmaps/<map>_radar_psd.vtex_c (console, 09.10): the source is a .psd
    tga = ensure_inside(s.content_addon / 'panorama' / 'images' / 'overheadmaps' / f'{name}_radar.psd', s.content_addon)
    tga.parent.mkdir(parents=True, exist_ok=True)
    write_psd(img, tga)
    old_tga = tga.with_suffix('.tga')
    if old_tga.is_file():
        old_tga.unlink()                         # an earlier generated radar under the wrong name
    lines = [MARK, '', f'"{name}"', '{', f'\t"material"\t"overviews/{name}"',
             f'\t"pos_x"\t\t"{pos_x:.0f}"', f'\t"pos_y"\t\t"{pos_y:.0f}"', f'\t"scale"\t\t"{scale:.3f}"']

    def norm(ent):
        o = ent.get('origin')
        return ((o[0] - pos_x) / (scale * SIZE), (pos_y - o[1]) / (scale * SIZE))
    for key, cls in (('CTSpawn', 'info_player_counterterrorist'), ('TSpawn', 'info_player_terrorist')):
        ents = m.entities(classname=cls)
        if ents:
            u, v = norm(ents[0])
            lines += [f'\t"{key}_x"\t"{u:.2f}"', f'\t"{key}_y"\t"{v:.2f}"']
    for ent in m.entities(classname='func_bomb_target'):
        site = 'A' if str(ent['entity_properties'].get('bomb_site_designation', '0')) == '0' else 'B'
        meshes = [c for c in m.iter_nodes(ent) if c.type == 'CMapMesh']
        if meshes:
            from . import checks
            b = checks._mesh_bounds(meshes[0])
            if b:
                cx_, cy_ = (b[0][0] + b[1][0]) / 2, (b[0][1] + b[1][1]) / 2
                lines += [f'\t"bomb{site}_x"\t"{(cx_ - pos_x) / (scale * SIZE):.2f}"',
                          f'\t"bomb{site}_y"\t"{(pos_y - cy_) / (scale * SIZE):.2f}"']
    lines.append('}')
    text = '\n'.join(lines) + '\n'
    for target in (overview, ensure_inside(s.content_addon / 'resource' / 'overviews' / f'{name}.txt', s.content_addon)):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding='utf-8')
    # resourcecompiler has no compiler for a bare image: a hidden layout that shows it compiles it as a dependency
    # (panorama/images/overheadmaps/<map>_radar.tga -> <map>_radar_tga.vtex_c, the name CS2 looks for).
    from . import mechanics
    xml = (f'<root><Panel class="Hidden"><Image src="file://{{images}}/overheadmaps/{name}_radar.psd" /></Panel></root>')
    mechanics.ensure_hud(project, f'mcp_radar_{name}', xml, '.Hidden { visibility: collapse; }')
    compiled = (s.game_addon / 'panorama' / 'images' / 'overheadmaps' / f'{name}_radar_psd.vtex_c').is_file()
    return {'radar': s.addon_relative(tga), 'overview': f'resource/overviews/{name}.txt',
            'scale': round(scale, 3), 'compiled': compiled}
